"""Generate the Elden Ring place name table from the installed game data.

Usage:
    python gen_places.py "<...>/ELDEN RING/Game" <repo root>

Writes:
    src/parse/EldenRing/PlaceNames.h      table size
    src/parse/EldenRing/PlaceNames.cpp    PlaceName text by id

Names come from PlaceName.fmg in /msg/engus/item*.msgbnd (base game and DLC). The
"Load Game" screen shows PlaceName[id] where id is the u32 at +0x32 of the slot's profile
summary in USER_DATA010: region ids (61001 Stormhill, 63002 Capital Outskirts, 65000
Mountaintops of the Giants) or a legacy dungeon's area * 1000 + block * 10 (11050
Leyndell, Ashen Capital, 13000 Crumbling Farum Azula). Larger ids are map point and play
region names; all are kept.

Requires pycryptodome and zstandard.
"""
import os
import re
import sys

import erdata

MSGBNDS = ("/msg/engus/item.msgbnd.dcx", "/msg/engus/item_dlc01.msgbnd.dcx", "/msg/engus/item_dlc02.msgbnd.dcx")


def cpp_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def load_places(archives):
    places = {}
    for path in MSGBNDS:
        if not archives.has(path):
            continue
        for fmg_name, data in archives.bnd(path).items():
            if re.sub(r"_dlc\d+(?=\.fmg$)", "", fmg_name) != "PlaceName.fmg":
                continue
            for place_id, text in erdata.parse_fmg2(data).items():
                if text and not text.startswith("[ERROR]"):
                    places[place_id] = text
    return places


def main(game_dir, repo_root):
    places = load_places(erdata.Archives(game_dir))
    out_dir = os.path.join(repo_root, "src", "parse", "EldenRing")
    banner = "// Generated by tools/er_items/gen_places.py from /msg/engus/item*.msgbnd PlaceName.fmg; do not edit."

    header = [
        "#pragma once",
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        banner,
        "namespace fssm::parse::er {",
        "    struct PlaceName {",
        "        uint32_t id;",
        "        std::string_view name;",
        "    };",
        "",
        "    // PlaceName text, sorted by id.",
        f"    extern const std::array<PlaceName, {len(places)}> PLACE_NAMES;",
        "",
        "    // Name the \"Load Game\" screen shows for SlotSummary::placeNameId.",
        "    // Empty when the id is unknown.",
        "    std::string_view findPlaceName(uint32_t placeNameId);",
        "}",
        "",
    ]
    source = [
        '#include "PlaceNames.h"',
        "",
        "#include <algorithm>",
        "",
        banner,
        "namespace fssm::parse::er {",
        f"    const std::array<PlaceName, {len(places)}> PLACE_NAMES = {{{{",
    ]
    source += [f"        {{{place_id}, {cpp_string(places[place_id])}}}," for place_id in sorted(places)]
    source += [
        "    }};",
        "",
        "    std::string_view findPlaceName(uint32_t placeNameId) {",
        "        const auto it = std::lower_bound(PLACE_NAMES.begin(), PLACE_NAMES.end(), placeNameId,",
        "            [](const PlaceName& place, uint32_t id) { return place.id < id; });",
        "        if (it == PLACE_NAMES.end() || it->id != placeNameId) return {};",
        "        return it->name;",
        "    }",
        "}",
        "",
    ]
    for name, lines in (("PlaceNames.h", header), ("PlaceNames.cpp", source)):
        with open(os.path.join(out_dir, name), "w", encoding="utf-8", newline="\r\n") as f:
            f.write("\n".join(lines))
    print(f"{len(places)} place names")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
