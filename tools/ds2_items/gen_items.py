"""Generate src/parse/DS2/Items.cpp from the installed Dark Souls II: SotFS game data.

Usage:
    python gen_items.py "<...>/Dark Souls II Scholar of the First Sin/Game" ../../src/parse/DS2/Items.cpp

Item names come from /menu/text/english/itemname.fmg, item kind and stack size from
ItemParam in enc_regulation.bnd.dcx. Rows without an English name are internal
placeholders and are skipped.
"""
import struct
import sys

import ds2data

# Top byte of ItemParam field 19 (ITEM_PARAM_ST +0x4c).
KIND_WEAPON = 0
KIND_SHIELD = 1
KIND_HEAD = 2
KIND_CHEST = 3
KIND_HANDS = 4
KIND_LEGS = 5
KIND_AMMO = 6
KIND_RING = 7
KIND_GOODS = 8
KIND_SPELL = 9
KIND_GESTURE = 10


def category(item_id, kind):
    if kind == KIND_WEAPON:
        if 3_800_000 <= item_id < 4_200_000 or 5_400_000 <= item_id < 5_500_000:
            return "Catalysts"      # staves, chimes, pyromancy flames
        if 4_200_000 <= item_id < 4_700_000:
            return "RangedWeapons"  # bows, greatbows, crossbows
        return "Weapons"
    if kind == KIND_GOODS:
        if 50_000_000 <= item_id < 54_000_000:
            return "KeyItems"
        if 60_970_000 <= item_id < 62_000_000:
            return "Materials"      # titanite, infusion stones
        return "Consumables"
    return {
        KIND_SHIELD: "Shields",
        KIND_HEAD: "HeadArmor",
        KIND_CHEST: "ChestArmor",
        KIND_HANDS: "HandsArmor",
        KIND_LEGS: "LegsArmor",
        KIND_AMMO: "Ammunition",
        KIND_RING: "Rings",
        KIND_SPELL: "Spells",
        KIND_GESTURE: "Gestures",
    }.get(kind, "Unknown")


def cpp_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main(game_dir, out_path):
    archive = ds2data.Archive(game_dir)
    names = ds2data.parse_fmg(archive.read("/menu/text/english/itemname.fmg"))
    params = ds2data.parse_bnd4(ds2data.read_regulation(game_dir))
    item_rows = ds2data.parse_param(params["ItemParam.param"])

    items = []
    for item_id, row in sorted(item_rows.items()):
        name = names.get(item_id)
        if not name or item_id < 1000:   # "No Item" / "No Spell" placeholders
            continue
        fields = struct.unpack("<21i", row)
        kind = (fields[19] >> 24) & 0xFF
        max_held = (fields[18] >> 16) & 0xFFFF
        order = fields[16] & 0xFFFF
        items.append((item_id, max_held, order, category(item_id, kind), name))

    lines = [
        "// Generated by tools/ds2_items/gen_items.py from the game's ItemParam and",
        "// /menu/text/english/itemname.fmg. Do not edit by hand.",
        '#include "Items.h"',
        "",
        "namespace fssm::parse::ds2 {",
        f"    const std::array<BaseItem, {len(items)}> ALL_ITEMS = {{",
    ]
    for item_id, max_held, order, cat, name in items:
        lines.append(f"        BaseItem{{{item_id}, {max_held}, {order}, ItemCategory::{cat}, {cpp_string(name)}}},")
    lines += ["    };", "}", ""]
    with open(out_path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(items)} items to {out_path}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
