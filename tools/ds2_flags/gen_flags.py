"""Generate the Dark Souls II: SotFS bonfire and boss tables from the installed game data.

Usage:
    python gen_flags.py "<...>/Dark Souls II Scholar of the First Sin/Game" <repo root>

Writes:
    src/parse/DS2/WorldProgress.h      table sizes
    src/parse/DS2/WorldProgress.cpp    areas, bonfires (MapObjectBonfireParam), bosses (BossBattleParam)

Bonfires are the MapObjectBonfireParam rows (regulation) with a name in
/menu/text/english/bonfirename.fmg (row id -> name). The save keeps them by row id in
SaveDataEvent (see EventData in src/parse/DS2/SaveData.h). Row layout used here: +0x10
map id of the bonfire's area (name from mapname.fmg, falling back to the map's base id),
+0x23 sort key of the game's warp list. Areas are listed in the order of their first
bonfire in that list.

Bosses are the BossBattleParam rows. When a boss dies the game sets the event flags at
+0x10 (per map) and +0x14 (group 10, global) and counts the kill under the index at
+0x18 (FUN_1401826d0); the tables use the global +0x14 flag. +0x2c/+0x30/+0x34 are name
ids in a text table whose archive path is unknown (looked up by its path hash), +0x3c is
the bonfire next to the boss, whose area the boss is listed under. Rows sharing a flag
(variants of one fight) are one entry.

Requires pycryptodome.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "ds2_items"))
import ds2data  # noqa: E402

# Text table with the names shown on boss health bars (49 entries, e.g. 3096 "The Last Giant").
BOSS_NAME_FMG_HASH = 0xE4F0B417

# Bonfires whose +0x10 map names the wrong area (their warp list position agrees with these).
BONFIRE_AREA_OVERRIDES = {
    17665: "Harvest Valley",    # Poison Pool, +0x10 says Earthen Peak
    29650: "Shaded Woods",      # Old Akelarre, +0x10 says Majula
}

# BossBattleParam row -> name, for fights with several bosses or a misleading health bar name.
BOSS_NAME_OVERRIDES = {
    1014010: "Prowling Magus and Congregation",
    1016000: "Ruin Sentinels",
    1021000: "Twin Dragonriders",
    1021020: "Throne Watcher and Defender",
    5030020: "Graverobber, Varg and Cerah",
    5036020: "Blue Smelter Demon",
    5037010: "Lud and Zallen, the King's Pets",
}


def cpp_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def area_name(map_names, map_id):
    for key in (map_id, map_id // 10000 * 10000):
        if key in map_names:
            return map_names[key].strip()
    raise KeyError(f"no map name for {map_id}")


def main(game_dir, repo_root):
    archive = ds2data.Archive(game_dir)
    bonfire_names = ds2data.parse_fmg(archive.read("/menu/text/english/bonfirename.fmg"))
    map_names = ds2data.parse_fmg(archive.read("/menu/text/english/mapname.fmg"))
    boss_names = ds2data.parse_fmg(archive.read_hash(BOSS_NAME_FMG_HASH))
    params = ds2data.parse_bnd4(ds2data.read_regulation(game_dir))

    bonfires = []   # (sort key, row id, area name, name)
    for row_id, data in ds2data.parse_param(params["MapObjectBonfireParam.param"]).items():
        if row_id not in bonfire_names:
            continue
        map_id = struct.unpack_from("<i", data, 0x10)[0]
        area = BONFIRE_AREA_OVERRIDES.get(row_id) or area_name(map_names, map_id)
        bonfires.append((data[0x23], row_id, area, bonfire_names[row_id].strip()))
    bonfires.sort()
    areas = []
    for _, _, area, _ in bonfires:
        if area not in areas:
            areas.append(area)
    bonfire_area = {row_id: area for _, row_id, area, _ in bonfires}

    bosses = []     # (area index, row id, flag, name)
    seen_flags = set()
    for row_id, data in ds2data.parse_param(params["BossBattleParam.param"]).items():
        flag = struct.unpack_from("<I", data, 0x14)[0]
        if flag == 0 or flag in seen_flags:
            continue
        seen_flags.add(flag)
        name_ids = struct.unpack_from("<3I", data, 0x2C)
        bonfire = struct.unpack_from("<I", data, 0x3C)[0]
        name = BOSS_NAME_OVERRIDES.get(row_id) or boss_names[name_ids[0]].strip()
        bosses.append((areas.index(bonfire_area[bonfire]), row_id, flag, name))
    bosses.sort()

    header = [
        "#pragma once",
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "// Generated by tools/ds2_flags/gen_flags.py, do not edit.",
        "namespace fssm::parse::ds2 {",
        "    struct Bonfire {",
        "        uint16_t id;                    // MapObjectBonfireParam row, EventData::bonfireIds",
        "        uint8_t area;                   // index into AREAS",
        "        std::string_view name;",
        "    };",
        "",
        "    struct Boss {",
        "        uint32_t flagId;                // event flag (group 10) set when defeated",
        "        uint8_t area;                   // index into AREAS",
        "        std::string_view name;",
        "    };",
        "",
        "    // Areas in the order of the warp list.",
        f"    extern const std::array<std::string_view, {len(areas)}> AREAS;",
        "    // Bonfires in warp list order.",
        f"    extern const std::array<Bonfire, {len(bonfires)}> BONFIRES;",
        "    // Bosses grouped by the area of the bonfire next to them.",
        f"    extern const std::array<Boss, {len(bosses)}> BOSSES;",
        "}",
    ]
    source = [
        '#include "WorldProgress.h"',
        "",
        "// Generated by tools/ds2_flags/gen_flags.py, do not edit.",
        "namespace fssm::parse::ds2 {",
        f"    const std::array<std::string_view, {len(areas)}> AREAS = {{",
        *[f"        {cpp_string(a)}," for a in areas],
        "    };",
        "",
        f"    const std::array<Bonfire, {len(bonfires)}> BONFIRES = {{",
        *[f"        Bonfire{{{row_id}, {areas.index(area)}, {cpp_string(name)}}},"
          for _, row_id, area, name in bonfires],
        "    };",
        "",
        f"    const std::array<Boss, {len(bosses)}> BOSSES = {{",
        *[f"        Boss{{{flag}, {area}, {cpp_string(name)}}},"
          for area, _, flag, name in bosses],
        "    };",
        "}",
    ]
    out_dir = os.path.join(repo_root, "src", "parse", "DS2")
    for name, lines in (("WorldProgress.h", header), ("WorldProgress.cpp", source)):
        with open(os.path.join(out_dir, name), "w", encoding="utf-8", newline="\r\n") as f:
            f.write("\n".join(lines) + "\n")
    print(f"{len(areas)} areas, {len(bonfires)} bonfires, {len(bosses)} bosses")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(2)
    main(sys.argv[1], sys.argv[2])
