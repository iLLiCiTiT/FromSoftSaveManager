#pragma once
#include <array>
#include <cstdint>

namespace fssm::parse::sekiro {
    // One node of the game's Acquire Skills screen (a SkillParam row).
    struct SkillNode {
        int32_t rowId = 0;          // SkillParam row id, referenced by prerequisites
        uint32_t itemId = 0;        // skill item as stored in the inventory once learned (see ALL_ITEMS)
        uint8_t tree = 0;           // 0 Shinobi Arts, 1 Prosthetic Arts, 2 Ashina Arts, 3 Temple Arts, 4 Mushin Arts
        uint8_t column = 0;         // left to right
        uint8_t row = 0;            // top to bottom, 0..7
        std::array<int32_t, 2> prerequisites{};  // rowIds, -1 for none
    };

    constexpr int SKILL_TREE_COUNT = 5;

    // Generated by tools/sekiro_items/gen_items.py
    extern const std::array<SkillNode, 46> SKILL_TREE;
}
