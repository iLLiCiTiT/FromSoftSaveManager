#pragma once
#include <array>
#include <cstdint>
#include <optional>
#include <string_view>
#include <vector>

#include "SaveData.h"

namespace fssm::parse::sekiro {
    // Assigned by item id range (see tools/sekiro_items/gen_items.py).
    enum class ItemCategory {
        QuickItems,
        KeyItems,
        Materials,
        PrayerBeads,
        Memories,
        SpiritEmblems,
        ProstheticTools,
        CombatArts,
        Unknown,
    };

    struct BaseItem {
        uint32_t id = 0;            // type nibble << 28 | param row id, as stored in the save
        ItemCategory category = ItemCategory::Unknown;
        std::string_view label = "Unknown";
        std::string_view image;     // alias in :/sekiro_inv_images (160x160), empty if none
    };

    // Generated by tools/sekiro_items/gen_items.py
    extern const std::array<BaseItem, 412> ALL_ITEMS;

    std::optional<BaseItem> findBaseItem(uint32_t id);

    // An inventory entry resolved against the item database.
    struct InventoryItem {
        uint32_t itemId = 0;
        uint32_t quantity = 0;
        bool keyItem = false;       // from the key item list
        bool knownItem = false;
        BaseItem baseItem;
    };

    // Items the game shows: entries with a known, named item.
    std::vector<InventoryItem> decode_inventory(const ItemList& list);
}
